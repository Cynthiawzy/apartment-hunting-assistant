/** Mirrors the backend's filtering logic (budget/beds/baths/radius) against the fixture data. */
export function filterMockListings(filters: ListingFilters, center: GeoPoint): Listing[] {
  return MOCK_LISTINGS.filter((listing) => listing.status === 'active')
    .filter((listing) => filters.budgetMax === undefined || listing.price <= filters.budgetMax)
    .filter((listing) => filters.minBeds === undefined || listing.bedrooms >= filters.minBeds)
    .filter(
      (listing) =>
        filters.minBathrooms === undefined ||
        (listing.bathrooms !== null && listing.bathrooms >= filters.minBathrooms),
    )
    .map((listing): Listing => {
      if (filters.radiusKm === undefined) return listing
      const distance_km = haversineDistanceKm(center, {
        latitude: listing.latitude,
        longitude: listing.longitude,
      })
      return { ...listing, distance_km }
    })
    .filter((listing) => filters.radiusKm === undefined || (listing.distance_km ?? 0) <= filters.radiusKm)
    .sort((a, b) => (a.distance_km ?? 0) - (b.distance_km ?? 0))
}
